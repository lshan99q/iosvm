"""Embed compiled SPIR-V modules as uint32_t arrays in one C header.

    python3 embed_spirv.py -o build/wp2_shaders.h build/spv/a.spv build/spv/b.spv ...

The header is generated at build time (Makefile) and included by metalwire_host.c, so the host is
one self-contained binary: no shader files to locate at run time, and `make test` needs nothing but
the compiler once the shaders are built.
"""

import argparse
import os
import struct
import sys


def c_name(path):
    base = os.path.basename(path)
    for suffix in (".vert.spv", ".frag.spv", ".spv"):
        if base.endswith(suffix):
            base = base[: -len(suffix)]
            break
    name = ""
    for ch in base:
        name += ch if ch.isalnum() else "_"
    return name


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("-o", "--output", required=True)
    parser.add_argument("inputs", nargs="+")
    args = parser.parse_args()

    modules = []
    for path in args.inputs:
        with open(path, "rb") as handle:
            data = handle.read()
        if len(data) == 0 or len(data) % 4 != 0:
            sys.exit(f"embed_spirv: {path}: {len(data)} bytes is not whole SPIR-V words")
        words = struct.unpack(f"<{len(data) // 4}I", data)
        modules.append((c_name(path), path, words))

    lines = [
        "/* SPDX-License-Identifier: MIT */",
        "/* Generated by embed_spirv.py from the shaders/ Vulkan GLSL. Do not edit. */",
        "#ifndef METALWIRE_WP2_SHADERS_H",
        "#define METALWIRE_WP2_SHADERS_H",
        "",
        "#include <stdint.h>",
        "",
        "struct mw_spirv_blob {",
        "    const char *name;",
        "    const uint32_t *words;",
        "    uint32_t word_count;",
        "};",
        "",
    ]
    for name, path, words in modules:
        lines.append(f"/* {path}: {len(words)} SPIR-V words */")
        lines.append(f"static const uint32_t mw_spirv_{name}[] = {{")
        for i in range(0, len(words), 8):
            lines.append("    " + ", ".join(f"0x{w:08x}u" for w in words[i : i + 8]) + ",")
        lines.append("};")
        lines.append("")
    lines.append("static const struct mw_spirv_blob mw_spirv_blobs[] = {")
    for name, _, words in modules:
        lines.append(f'    {{"{name}", mw_spirv_{name}, {len(words)}u}},')
    lines.append("};")
    lines.append("")
    lines.append("#endif /* METALWIRE_WP2_SHADERS_H */")
    lines.append("")

    tmp = args.output + ".tmp"
    with open(tmp, "w") as handle:
        handle.write("\n".join(lines))
    os.replace(tmp, args.output)
    print(f"embed_spirv: {args.output}: {len(modules)} module(s)")


if __name__ == "__main__":
    main()
