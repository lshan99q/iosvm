"""metalwire_gen -- a synthetic metalwire client, for testing the host translator without a guest.

It speaks the protocol in metalwire_protocol.h directly: create one buffer and one texture, then
for each frame upload a deterministic BGRA8 (or RGBA8) picture, record the buffer->texture blit,
present, end the frame, and wait for the host's acknowledgement.

The picture is fixed for a given (width, height, frame index), so the host's read-back and the
CRC-32 are meaningful, and the same picture can be regenerated by a test:

  * background: a diagonal gradient that scrolls by 11 rows per frame (the "moving" part),
  * border: an 8-pixel solid red frame,
  * frame counter: 32 bits as 8x4 blocks of 20x20 pixels near the top-left, white = 1,
  * marker: a yellow 96x96 square that moves 37 pixels per frame along the middle row.

Bytes are in the wire's memory order: BGRA by default, RGBA with --format rgba8. The CRC covers
exactly width*height*4 bytes, no row padding -- the same bytes the guest-side client hashes.

    ./metalwire_gen.py 750 1624 --frames 100 --port 9111
    ./metalwire_gen.py 750 1624 --frames 1 --bad-crc-at 0   # prove the CRC check bites
"""

import argparse
import functools
import os
import socket
import struct
import sys
import time
import zlib

MW_MAGIC = 0x4D575452  # "MWTR"
MW_ACK_MAGIC = 0x4D57414B  # "MWAK"
MW_VERSION = 2

MW_HELLO = 0x0001
MW_BYE = 0x0002
MW_CREATE_BUFFER = 0x0010
MW_UPLOAD_BUFFER = 0x0011
MW_CREATE_TEXTURE = 0x0020
MW_COPY_BUFFER_TO_TEXTURE = 0x0030
MW_PRESENT = 0x0040
MW_FRAME_BEGIN = 0x0050
MW_FRAME_END = 0x0051

MW_STATUS_OK = 0
MW_STATUS_CRC_MISMATCH = 4

BORDER = 8
MARKER = 96
MARKER_STEP = 37
SCROLL_STEP = 11

MSG_HEADER = struct.Struct("<IHHII")
ACK = struct.Struct("<IHHQQQIIIIII")  # exactly struct mw_ack


@functools.lru_cache(maxsize=8)
def _base_picture(width, height, bgra):
    """The static diagonal gradient the moving picture is made from."""
    buf = bytearray(width * height * 4)
    has_x = width > 1
    has_y = height > 1
    index = 0
    for y in range(height):
        fy = (y * 255) // (height - 1) if has_y else 0
        for x in range(width):
            fx = (x * 255) // (width - 1) if has_x else 0
            r = (fx + fy) // 2
            g = fy
            b = 255 - fx
            if bgra:
                buf[index] = b
                buf[index + 1] = g
                buf[index + 2] = r
            else:
                buf[index] = r
                buf[index + 1] = g
                buf[index + 2] = b
            buf[index + 3] = 255
            index += 4
    return bytes(buf)


def make_picture(width, height, frame, bgra=True):
    """The deterministic picture for one frame, in the wire's byte order."""
    if width < 64 or height < 64:
        raise ValueError("width and height must be at least 64")
    base = _base_picture(width, height, bgra)
    stride = width * 4
    shift = (frame * SCROLL_STEP) % height
    picture = bytearray(base[shift * stride :] + base[: shift * stride])

    def fill(x0, y0, x1, y1, b, g, r):
        x0 = max(0, x0)
        x1 = min(width, x1)
        if x1 <= x0:
            return
        pixel = (bytes((b, g, r, 255)) if bgra else bytes((r, g, b, 255)))
        row = pixel * (x1 - x0)
        for y in range(max(0, y0), min(height, y1)):
            at = y * width * 4 + x0 * 4
            picture[at : at + len(row)] = row

    # Solid red border (BGRA 0,0,255 / RGBA 255,0,0).
    red = (0, 0, 255) if bgra else (255, 0, 0)
    fill(0, 0, width, BORDER, *red)
    fill(0, height - BORDER, width, height, *red)
    fill(0, 0, BORDER, height, *red)
    fill(width - BORDER, 0, width, height, *red)

    # The 32-bit frame counter, 8 columns x 4 rows of 20x20 blocks.
    block = 20
    pitch = 24
    for bit in range(32):
        on = (frame >> bit) & 1
        x = 16 + (bit % 8) * pitch
        y = 16 + (bit // 8) * pitch
        value = (255, 255, 255) if on else (0, 0, 0)
        fill(x, y, x + block, y + block, *value)

    # The marker: one square that moves along the middle, so a saved frame is obvious to a human.
    span = width - 2 * BORDER - MARKER
    if span > 0:
        x0 = BORDER + (frame * MARKER_STEP) % span
        y0 = height // 2 - MARKER // 2
        marker = (0, 255, 255) if bgra else (255, 255, 0)
        fill(x0, y0, x0 + MARKER, y0 + MARKER, *marker)
    return bytes(picture)


class WireError(RuntimeError):
    pass


class Client:
    def __init__(self, host, port, timeout):
        self.sock = socket.create_connection((host, port), timeout=timeout)
        self.sock.settimeout(timeout)
        self.sock.setsockopt(socket.IPPROTO_TCP, socket.TCP_NODELAY, 1)
        self.timeout = timeout

    def close(self):
        try:
            self.sock.close()
        except OSError:
            pass

    def send(self, message_type, payload=b""):
        self.sock.sendall(MSG_HEADER.pack(MW_MAGIC, MW_VERSION, message_type, len(payload), 0))
        if payload:
            self.sock.sendall(payload)

    def _recv_exactly(self, size):
        data = bytearray()
        while len(data) < size:
            chunk = self.sock.recv(size - len(data))
            if not chunk:
                raise WireError("host closed the connection during a %d-byte read" % size)
            data += chunk
        return bytes(data)

    def recv_ack(self):
        return ACK.unpack(self._recv_exactly(ACK.size))


def main(argv):
    parser = argparse.ArgumentParser(
        description="Send deterministic synthetic frames to a metalwire host.")
    parser.add_argument("width", nargs="?", type=int, default=750)
    parser.add_argument("height", nargs="?", type=int, default=1624)
    parser.add_argument("--frames", type=int, default=10)
    parser.add_argument("--host", default="127.0.0.1")
    parser.add_argument("--port", type=int, default=9111)
    parser.add_argument("--format", choices=("bgra8", "rgba8"), default="bgra8",
                        help="Metal pixel format the texture is created with")
    parser.add_argument("--bad-crc-at", type=int, default=-1, metavar="INDEX",
                        help="deliberately send a wrong CRC for this frame index")
    parser.add_argument("--timeout", type=float, default=10.0,
                        help="socket timeout in seconds (default 10)")
    args = parser.parse_args(argv)
    if args.frames <= 0:
        parser.error("--frames must be positive")
    if args.width < 64 or args.height < 64:
        parser.error("width and height must be at least 64")
    if args.bad_crc_at >= args.frames:
        parser.error("--bad-crc-at must name a frame that is sent")
    bgra = args.format == "bgra8"
    pixel_format = 80 if bgra else 70
    bytes_per_row = args.width * 4
    picture_bytes = args.width * args.height * 4

    try:
        client = Client(args.host, args.port, args.timeout)
    except OSError as exc:
        print("metalwire_gen: cannot connect to %s:%d: %s" % (args.host, args.port, exc),
              file=sys.stderr)
        return 2

    encoded = []
    round_trips = []
    failures = 0
    started = time.monotonic_ns()
    try:
        client.send(MW_HELLO, struct.pack("<II32s", MW_VERSION, os.getpid(), b"metalwire_gen"))
        client.send(MW_CREATE_BUFFER, struct.pack("<IIQ", 1, 0, picture_bytes))
        client.send(MW_CREATE_TEXTURE,
                    struct.pack("<IIIIII", 1, args.width, args.height, pixel_format, 0, 0))

        for frame in range(args.frames):
            seq = frame
            begin = time.monotonic_ns()
            picture = make_picture(args.width, args.height, frame, bgra)
            crc = zlib.crc32(picture) & 0xFFFFFFFF
            sent_crc = (crc ^ 0xDEADBEEF) if frame == args.bad_crc_at else crc
            client.send(MW_FRAME_BEGIN, struct.pack("<QQ", seq, begin))
            client.send(MW_UPLOAD_BUFFER,
                        struct.pack("<IIII", 1, 0, len(picture), 0) + picture)
            client.send(MW_COPY_BUFFER_TO_TEXTURE,
                        struct.pack("<IIQIIIIII", 1, 1, 0, bytes_per_row, len(picture),
                                    args.width, args.height, 0, 0))
            client.send(MW_PRESENT, struct.pack("<II", 1, 0))
            encoded_ns = time.monotonic_ns() - begin
            client.send(MW_FRAME_END,
                        struct.pack("<QQIIII", seq, encoded_ns, sent_crc, args.width,
                                    args.height, bytes_per_row))
            ack = client.recv_ack()
            round_trip_ns = time.monotonic_ns() - begin
            (magic, version, status, ack_seq, _guest_commit, _host_done, ack_crc, crc_ok,
             ack_width, ack_height, ack_row_bytes, _reserved) = ack
            expected_ok = 0 if frame == args.bad_crc_at else 1
            expected_status = MW_STATUS_CRC_MISMATCH if frame == args.bad_crc_at else MW_STATUS_OK
            problems = []
            if magic != MW_ACK_MAGIC or version != MW_VERSION:
                problems.append("bad ack header magic=0x%08x version=%u" % (magic, version))
            if ack_seq != seq:
                problems.append("ack seq %d, expected %d" % (ack_seq, seq))
            if ack_width != args.width or ack_height != args.height or ack_row_bytes != bytes_per_row:
                problems.append("ack geometry %dx%d row %d" %
                                (ack_width, ack_height, ack_row_bytes))
            if ack_crc != crc:
                problems.append("host read back 0x%08x, sent 0x%08x" % (ack_crc, crc))
            if crc_ok != expected_ok:
                problems.append("crc_ok=%d, expected %d" % (crc_ok, expected_ok))
            if status != expected_status:
                problems.append("status=%d, expected %d" % (status, expected_status))
            if problems:
                failures += 1
                print("frame %d: FAIL: %s" % (frame, "; ".join(problems)), flush=True)
            else:
                encoded.append(encoded_ns)
                round_trips.append(round_trip_ns)
                print("frame %d: %d bytes, encoded %.3f ms, round-trip %.3f ms, "
                      "status=%s crc_ok=%d crc=0x%08x" %
                      (frame, len(picture), encoded_ns / 1e6, round_trip_ns / 1e6,
                       "ok" if status == MW_STATUS_OK else "crc-mismatch", crc_ok, crc),
                      flush=True)
        client.send(MW_BYE)
    except (OSError, WireError) as exc:
        print("metalwire_gen: wire error: %s" % exc, file=sys.stderr)
        failures += 1
    finally:
        client.close()

    elapsed = (time.monotonic_ns() - started) / 1e9
    sent = args.frames
    def stats(values):
        if not values:
            return 0.0, 0.0, 0.0
        return (sum(values) / len(values) / 1e6, min(values) / 1e6, max(values) / 1e6)

    enc_mean, enc_min, enc_max = stats(encoded)
    rt_mean, rt_min, rt_max = stats(round_trips)
    print("summary: %d/%d frame(s) acknowledged, %.3f s, %.1f fps; "
          "encoded mean/min/max %.3f/%.3f/%.3f ms; round-trip mean/min/max %.3f/%.3f/%.3f ms" %
          (sent - failures, sent, elapsed, sent / elapsed if elapsed > 0 else 0.0,
           enc_mean, enc_min, enc_max, rt_mean, rt_min, rt_max), flush=True)
    return 0 if failures == 0 else 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
